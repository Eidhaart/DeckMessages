#!/usr/bin/env bash
# DeckMessages server installer.
#
# Sets up, on a fresh Ubuntu/Debian VM (e.g. Oracle Cloud Always Free):
#   Synapse (Matrix homeserver) + mautrix-meta (Messenger bridge) + Postgres + Caddy (HTTPS)
#
# Usage:  curl -fsSL <raw url of this file> | sudo bash
#         sudo bash install.sh [--domain matrix.example.com] [--user deck]
#
# Without --domain it uses a free <your-ip>.sslip.io hostname, so no domain is needed.
# Safe to re-run: existing secrets, accounts and chats are kept.

set -euo pipefail

# Everything runs inside main(), so bash has read the whole script before running any of it.
# With `curl ... | bash`, a command that reads stdin (like `docker compose run`) would
# otherwise swallow the rest of the script and the install would silently stop.
main() {

local DIR DOMAIN MXUSER
DIR=/opt/deckmessages
DOMAIN="${DECK_DOMAIN:-}"
MXUSER="${DECK_USER:-deck}"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --domain) DOMAIN="$2"; shift 2 ;;
    --user) MXUSER="$2"; shift 2 ;;
    --dir) DIR="$2"; shift 2 ;;
    *) echo "unknown option: $1" >&2; exit 1 ;;
  esac
done

c_on=$'\e[1;36m'; c_pk=$'\e[1;35m'; c_off=$'\e[0m'
step() { echo "${c_pk}▶${c_off} ${c_on}$*${c_off}"; }
die() { echo "!! $*" >&2; exit 1; }

[[ $EUID -eq 0 ]] || die "run as root: sudo bash install.sh"
command -v apt-get >/dev/null || die "this installer supports Ubuntu/Debian only"
[[ "$MXUSER" =~ ^[a-z0-9._=-]+$ ]] || die "--user may only contain a-z 0-9 . _ = -"

# ---------------------------------------------------------------- prerequisites
step "Installing prerequisites"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq curl openssl ca-certificates >/dev/null

if ! command -v docker >/dev/null; then
  step "Installing Docker"
  curl -fsSL https://get.docker.com | sh >/dev/null
fi
docker compose version >/dev/null 2>&1 || die "docker compose plugin missing"

# Small VMs (1 GB) need swap for Synapse + Postgres.
mem_mb=$(awk '/MemTotal/ {print int($2/1024)}' /proc/meminfo)
if (( mem_mb < 2000 )) && ! swapon --show | grep -q .; then
  step "Adding 2 GB swap (only ${mem_mb} MB RAM)"
  fallocate -l 2G /swapfile && chmod 600 /swapfile && mkswap /swapfile >/dev/null && swapon /swapfile
  grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi

# ---------------------------------------------------------------- firewall
step "Opening ports 80 and 443"
# Oracle's Ubuntu images ship iptables rules that reject everything but SSH.
if command -v iptables >/dev/null && iptables -S INPUT 2>/dev/null | grep -q -- '-j REJECT'; then
  for p in 80 443; do
    iptables -C INPUT -p tcp --dport $p -j ACCEPT 2>/dev/null || iptables -I INPUT 1 -p tcp --dport $p -j ACCEPT
  done
  command -v netfilter-persistent >/dev/null && netfilter-persistent save >/dev/null 2>&1 || true
fi
if command -v ufw >/dev/null && ufw status | grep -q "Status: active"; then
  ufw allow 80/tcp >/dev/null && ufw allow 443/tcp >/dev/null
fi

# ---------------------------------------------------------------- settings
mkdir -p "$DIR" && cd "$DIR"
if [[ -f .env ]]; then
  # shellcheck disable=SC1091
  source .env
  step "Existing install found for ${DOMAIN}, updating"
else
  if [[ -z "$DOMAIN" ]]; then
    ip=$(curl -fsS4 --max-time 10 https://api.ipify.org || curl -fsS4 --max-time 10 https://ifconfig.me) \
      || die "couldn't detect the public IP; pass --domain"
    DOMAIN="${ip//./-}.sslip.io"
  fi
  PG_PASS=$(openssl rand -hex 16)
  USER_PASS=$(openssl rand -base64 18 | tr -dc 'A-Za-z0-9' | head -c 16)
  cat > .env <<EOF
DOMAIN=$DOMAIN
MXUSER=$MXUSER
PG_PASS=$PG_PASS
USER_PASS=$USER_PASS
EOF
  chmod 600 .env
fi

step "Writing config for ${DOMAIN}"
mkdir -p synapse bridge postgres caddy

cat > docker-compose.yml <<'EOF'
# Generated by DeckMessages install.sh
services:
  postgres:
    image: postgres:16-alpine
    restart: unless-stopped
    environment:
      POSTGRES_USER: deck
      POSTGRES_PASSWORD: ${PG_PASS}
      POSTGRES_DB: synapse
      POSTGRES_INITDB_ARGS: "--encoding=UTF8 --locale=C"
    volumes:
      - ./postgres:/var/lib/postgresql/data
      - ./init-db.sql:/docker-entrypoint-initdb.d/init-db.sql:ro
    healthcheck:
      test: ["CMD", "pg_isready", "-U", "deck"]
      interval: 5s
      retries: 20

  synapse:
    image: matrixdotorg/synapse:latest
    restart: unless-stopped
    depends_on:
      postgres: { condition: service_healthy }
    volumes:
      - ./synapse:/data
    ports:
      - "127.0.0.1:8008:8008"

  mautrix-meta:
    image: dock.mau.dev/mautrix/meta:latest
    restart: unless-stopped
    depends_on:
      postgres: { condition: service_healthy }
    volumes:
      - ./bridge:/data

  caddy:
    image: caddy:2-alpine
    restart: unless-stopped
    ports:
      - "80:80"
      - "443:443"
    volumes:
      - ./Caddyfile:/etc/caddy/Caddyfile:ro
      - ./caddy:/data
EOF

echo "CREATE DATABASE mautrix_meta;" > init-db.sql

cat > Caddyfile <<EOF
${DOMAIN} {
	reverse_proxy /_matrix/* synapse:8008
	reverse_proxy /_synapse/client/* synapse:8008
	respond / "DeckMessages server online" 200
}
EOF

compose() { docker compose --env-file .env "$@"; }

step "Pulling images (first time takes a few minutes)"
compose pull -q

# ---------------------------------------------------------------- synapse
if [[ ! -f synapse/homeserver.yaml ]]; then
  step "Generating Synapse config"
  compose run --rm --no-deps -e SYNAPSE_SERVER_NAME="$DOMAIN" -e SYNAPSE_REPORT_STATS=no synapse generate >/dev/null
fi

step "Configuring Synapse"
compose run --rm -T --no-deps -e PG_PASS="$PG_PASS" -e DOMAIN="$DOMAIN" --entrypoint python synapse - <<'PY'
import os, yaml
p = "/data/homeserver.yaml"
c = yaml.safe_load(open(p))
c["database"] = {
    "name": "psycopg2",
    "args": {"user": "deck", "password": os.environ["PG_PASS"], "database": "synapse",
             "host": "postgres", "cp_min": 2, "cp_max": 10},
}
c["public_baseurl"] = f"https://{os.environ['DOMAIN']}/"
# Only Caddy talks to Synapse, over the IPv4 Docker network; some VMs have no IPv6 at all.
for listener in c.get("listeners", []):
    listener["bind_addresses"] = ["0.0.0.0"]
c["enable_registration"] = False
c["app_service_config_files"] = ["/data/meta-registration.yaml"]
c["max_upload_size"] = "100M"
yaml.safe_dump(c, open(p, "w"), sort_keys=False)
PY

# ---------------------------------------------------------------- bridge
if [[ ! -f bridge/config.yaml ]]; then
  step "Generating bridge config"
  compose run --rm --no-deps mautrix-meta >/dev/null
fi

step "Configuring Messenger bridge"
compose run --rm --no-deps -e DOMAIN="$DOMAIN" -e MXUSER="$MXUSER" \
  -e DB_URI="postgres://deck:${PG_PASS}@postgres/mautrix_meta?sslmode=disable" \
  --entrypoint yq mautrix-meta -I4 -i '
    .homeserver.address = "http://synapse:8008" |
    .homeserver.domain = strenv(DOMAIN) |
    .appservice.address = "http://mautrix-meta:29319" |
    .appservice.hostname = "0.0.0.0" |
    .database.type = "postgres" |
    .database.uri = strenv(DB_URI) |
    .bridge.permissions = {strenv(DOMAIN): "user", ("@" + strenv(MXUSER) + ":" + strenv(DOMAIN)): "admin"} |
    .encryption.allow = false |
    .backfill.enabled = true |
    .backfill.max_initial_messages = 100 |
    .network.e2ee_backfill = true
  ' /data/config.yaml

if [[ ! -f bridge/registration.yaml ]]; then
  compose run --rm --no-deps mautrix-meta >/dev/null
fi
cp bridge/registration.yaml synapse/meta-registration.yaml
chown 991:991 synapse/meta-registration.yaml

# ---------------------------------------------------------------- start
step "Starting services"
compose up -d --remove-orphans >/dev/null

for i in $(seq 1 90); do
  curl -fsS http://127.0.0.1:8008/health >/dev/null 2>&1 && break
  [[ $i -eq 90 ]] && die "Synapse didn't come up. Check: cd $DIR && docker compose logs synapse"
  sleep 2
done
compose restart mautrix-meta >/dev/null

# Create the account unless it exists (an earlier run may have stopped before this point).
if ! curl -fsS "http://127.0.0.1:8008/_matrix/client/v3/profile/@${MXUSER}:${DOMAIN}" >/dev/null 2>&1; then
  step "Creating your account @${MXUSER}:${DOMAIN}"
  compose exec -T synapse register_new_matrix_user -c /data/homeserver.yaml \
    -u "$MXUSER" -p "$USER_PASS" --no-admin http://localhost:8008 </dev/null >/dev/null
fi

step "Waiting for HTTPS certificate"
https_ok=0
for i in $(seq 1 45); do
  if curl -fsS --max-time 5 "https://${DOMAIN}/_matrix/client/versions" >/dev/null 2>&1; then https_ok=1; break; fi
  sleep 2
done

cat > credentials.txt <<EOF
homeserver:  https://${DOMAIN}
user:        ${MXUSER}
passphrase:  ${USER_PASS}
EOF
chmod 600 credentials.txt

echo
echo "${c_pk}╔══════════════════════════════════════════════════════════╗${c_off}"
echo "${c_pk}║${c_off}  ${c_on}DECK//MSG SERVER ONLINE${c_off}"
echo "${c_pk}╚══════════════════════════════════════════════════════════╝${c_off}"
echo "  Enter these in the DeckMessages login screen:"
echo
sed 's/^/    /' credentials.txt
echo
echo "  Then type /bridge, send: login   and follow the bot's steps."
echo "  (Saved in ${DIR}/credentials.txt. Show again: sudo cat ${DIR}/credentials.txt)"
if (( ! https_ok )); then
  echo
  echo "  !! https://${DOMAIN} isn't reachable yet. On Oracle Cloud, allow TCP 80 and 443"
  echo "     in the VCN security list (see docs/SERVER.md), then wait a minute."
fi
}

main "$@"
